#!/usr/bin/env python3
"""Embed libb2l-mesa.dylib (Mesa for iOS over B2LMali) in the kernel.

The library comes from the Mesa workflow (scripts/mesa, artifact b2l-mesa):
our code and Mesa (MIT) built against the public iOS SDK. It is far larger
than the GPU library, so it is zlib-compressed here and inflated by the
kernel (bsd/kern/b2l_mesa_seed.h), which publishes it at boot under a name
that carries its hash. Without --input, or with a missing file, the header
only defines B2L_HAS_MESA_PAYLOAD 0 and the kernel builds without it.
"""
import argparse
import hashlib
import pathlib
import zlib

LIMIT = 64 * 1024 * 1024        # what the kernel accepts, inflated


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--xnu', type=pathlib.Path, required=True)
    ap.add_argument('--input', type=pathlib.Path)
    a = ap.parse_args()
    header = a.xnu / 'bsd/kern/b2l_mesa_payload.h'
    if a.input is None or not a.input.is_file():
        header.write_text('/* Generated by scripts/build-mesa-payload.py: no Mesa library. */\n'
                          '#define B2L_HAS_MESA_PAYLOAD 0\n')
        print('no Mesa library: kernel built without it')
        return
    data = a.input.read_bytes()
    if not data.startswith(b'\xcf\xfa\xed\xfe') or len(data) > LIMIT:
        raise SystemExit('libb2l-mesa.dylib is not a 64-bit Mach-O under the size limit')
    packed = zlib.compress(data, 9)
    tag = hashlib.sha256(data).hexdigest()[:12]
    rows = [','.join('0x%02x' % b for b in packed[i:i + 24]) for i in range(0, len(packed), 24)]
    header.write_text(
        '/* Generated by scripts/build-mesa-payload.py; not repository content. */\n'
        '#define B2L_HAS_MESA_PAYLOAD 1\n'
        f'#define B2L_MESA_LIBRARY "/usr/local/lib/b2l-mesa-{tag}.dylib"\n'
        f'#define B2L_MESA_STAGING "/usr/local/lib/.b2l-mesa-{tag}"\n'
        f'#define B2L_MESA_BYTES {len(data)}u\n'
        'static const unsigned char b2l_mesa_compressed[] = {\n' + ',\n'.join(rows) + '\n};\n')
    print(f'Mesa library {len(data)} bytes, {len(packed)} compressed, {tag}, '
          f'sha256 {hashlib.sha256(data).hexdigest()}')


if __name__ == '__main__':
    main()
